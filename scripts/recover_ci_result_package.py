EXECUTION_STAGE_NAMES = [
    "checkout",
    "prepareMetadata",
    "bootstrap",
    "selectXcode",
    "staticChecks",
    "projectVerification",
    "macBuild",
    "iosBuild",
    "createManifest",
    "ensureResultPackage",
]


def env_outcome(name):
    value = os.environ.get(name, "unknown").strip()
    return value if value in ALLOWED_OUTCOMES else "unknown"


def write_json(path, value):
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def path_metadata(relative_path, required):
    path = Path(relative_path)
    entry = {"path": relative_path, "required": required, "exists": path.exists()}
    if path.is_file():
        entry.update({"kind": "file", "byteCount": path.stat().st_size})
    elif path.is_dir():
        files = [child for child in path.rglob("*") if child.is_file()]
        entry.update({
            "kind": "directory",
            "fileCount": len(files),
            "recursiveByteCount": sum(child.stat().st_size for child in files),
        })
    else:
        entry["kind"] = "missing"
    return entry


def reject_required_symlinks():
    symlinked_paths = sorted(
        path for path in REQUIRED_FAILURE_PATHS if Path(path).is_symlink()
    )
    if symlinked_paths:
        raise RuntimeError(
            "Recovered fallback package required paths must not be symlinks: "
            + ", ".join(symlinked_paths)
        )


def valid_required_entry(relative_path, entry):
    path = Path(relative_path)
    return (
        entry is not None
        and entry.get("required") is True
        and entry.get("exists") is True
        and entry.get("kind") == "file"
        and isinstance(entry.get("byteCount"), int)
        and entry["byteCount"] > 0
        and not path.is_symlink()
        and path.is_file()
    )


def log_excerpt(name, outcome):
    log_paths = {
        "prepareMetadata": "ci-results/prepare-metadata.log",
        "selectXcode": "ci-results/xcode-version.log",
        "staticChecks": "ci-results/static-checks.log",
        "projectVerification": "ci-results/verify_project.log",
        "macBuild": "ci-results/xcodebuild.log",
        "iosBuild": "ci-results/ios-xcodebuild.log",
    }
    log_path = log_paths.get(name)
    if not log_path:
        return [f"No artifact log generated for package stage {name} (step outcome: {outcome})"]
    path = Path(log_path)
    if not path.exists():
        return [f"No artifact log generated: {log_path} (step outcome: {outcome})"]
    lines = [" ".join(line.split()) for line in path.read_text(encoding="utf-8", errors="replace").splitlines() if line.strip()]
    return [f"tail: {line}" for line in lines[-8:]] or [f"No log content: {log_path}"]


def main():
    root = Path("ci-results")
    root.mkdir(parents=True, exist_ok=True)
    reject_required_symlinks()

    branch = os.environ.get("GITHUB_REF_NAME", "")
    commit = os.environ.get("GITHUB_SHA", "")
    run_id = os.environ.get("GITHUB_RUN_ID", "")
    attempt = os.environ.get("GITHUB_RUN_ATTEMPT", "")
    branch_slug = branch.replace("/", "-")
    short_sha = commit[:7]
    normal_name = f"chronofocus-ci-{os.environ['CI_PROCESS_VERSION']}-{branch_slug}-{short_sha}-run{run_id}-attempt{attempt}"
    fallback_name = f"chronofocus-ci-{os.environ['CI_PROCESS_VERSION']}-{branch_slug}-{commit}-run{run_id}-attempt{attempt}"
    artifact_name = fallback_name
    fallback_used = artifact_name != normal_name

    stage_outcomes = [
        ("checkout", env_outcome("CHECKOUT_OUTCOME")),
        ("prepareMetadata", env_outcome("PREPARE_METADATA_OUTCOME")),
        ("selectXcode", env_outcome("SELECT_XCODE_OUTCOME")),
        ("staticChecks", env_outcome("STATIC_OUTCOME")),
        ("projectVerification", env_outcome("PROJECT_VERIFY_OUTCOME")),
        ("macBuild", env_outcome("BUILD_OUTCOME")),
        ("iosBuild", env_outcome("IOS_BUILD_OUTCOME")),
    ]
    create_manifest = env_outcome("CREATE_MANIFEST_OUTCOME")
    ensure_result_package = env_outcome("ENSURE_RESULT_PACKAGE_OUTCOME")
    package_outcomes = [("bootstrap", env_outcome("SCAFFOLD_OUTCOME")), ("createManifest", create_manifest)]
    non_success = [name for name, outcome in stage_outcomes if outcome != "success"]
    failed = [name for name, outcome in stage_outcomes if outcome in {"failure", "cancelled", "unknown"}]
    non_success_package = [name for name, outcome in package_outcomes if outcome != "success"]
    failed_package = [name for name, outcome in package_outcomes if outcome in {"failure", "cancelled", "unknown"}]
    outcome_by_name = dict(stage_outcomes + package_outcomes + [("ensureResultPackage", ensure_result_package)])
    ordered_non_success = [name for name in EXECUTION_STAGE_NAMES if outcome_by_name[name] != "success"]
    ordered_failed = [
        name for name in EXECUTION_STAGE_NAMES
        if outcome_by_name[name] in {"failure", "cancelled", "unknown"}
    ]
    all_non_success = ordered_non_success
    first_failed = ordered_failed[0] if ordered_failed else (ordered_non_success[0] if ordered_non_success else None)
    failure_mode = os.environ.get("FAILURE_INJECTION", "none")
    if failure_mode == "none":
        failure_mode = "runtime"
    created_at = datetime.now(timezone.utc).isoformat()

    context = "".join([
        f"artifactName={artifact_name}\n",
        f"branch={branch}\n",
        f"commitSha={commit}\n",
        f"runId={run_id}\n",
        f"runAttempt={attempt}\n",
    ])
    (root / "ci-run-context.txt").write_text(context, encoding="utf-8")

    stages = [{"name": name, "outcome": outcome} for name, outcome in stage_outcomes]
    package_stages = [{"name": name, "outcome": outcome} for name, outcome in package_outcomes]
    stage_payload = {
        "version": os.environ["CI_PROCESS_VERSION"],
        "artifactName": artifact_name,
        "branch": branch,
        "commitSha": commit,
        "runId": run_id,
        "runAttempt": attempt,
        "createdAt": created_at,
        "overallOutcome": "failure",
        "failureMode": failure_mode,
        "fallbackArtifactName": fallback_name,
        "fallbackArtifactUsed": fallback_used,
        "firstFailedStage": first_failed,
        "failedStages": failed,
        "nonSuccessStages": non_success,
        "packageStages": package_stages,
        "failedPackageStages": failed_package,
        "nonSuccessPackageStages": non_success_package,
        "ensureResultPackageOutcome": ensure_result_package,
        "recoveryOutcome": "success",
        "stageOutcomeMap": {name: outcome for name, outcome in stage_outcomes},
        "stageOutcomes": {name: outcome for name, outcome in stage_outcomes},
        "stages": stages,
    }
    write_json(root / "ci-stage-outcomes.json", stage_payload)

    manifest = {
        "version": os.environ["CI_PROCESS_VERSION"],
        "artifactName": artifact_name,
        "branch": branch,
        "commitSha": commit,
        "shortSha": short_sha,
        "runId": run_id,
        "runAttempt": attempt,
        "workflowName": os.environ.get("GITHUB_WORKFLOW", "ChronoFocus CI Results"),
        "createdAt": created_at,
        "projectName": os.environ["PROJECT_NAME"],
        "scheme": os.environ["MAC_SCHEME"],
        "destination": os.environ["MAC_DESTINATION"],
        "macScheme": os.environ["MAC_SCHEME"],
        "macDestination": os.environ["MAC_DESTINATION"],
        "iosScheme": os.environ["IOS_SCHEME"],
        "iosDestination": os.environ["IOS_DESTINATION"],
        "resultBundlePath": "ci-results/ChronoFocusMac.xcresult",
        "macResultBundlePath": "ci-results/ChronoFocusMac.xcresult",
        "iosResultBundlePath": "ci-results/ChronoFocus-iOS.xcresult",
        "junitPath": "ci-results/junit.xml",
        "buildLogPath": "ci-results/xcodebuild.log",
        "macBuildLogPath": "ci-results/xcodebuild.log",
        "iosBuildLogPath": "ci-results/ios-xcodebuild.log",
        "failureSummaryPath": "ci-results/ci-failure-summary.md",
        "artifactIndexPath": "ci-results/ci-artifact-index.json",
        "stageOutcomesPath": "ci-results/ci-stage-outcomes.json",
        "overallOutcome": "failure",
        "failureMode": failure_mode,
        "fallbackArtifactName": fallback_name,
        "fallbackArtifactUsed": fallback_used,
        "firstFailedStage": first_failed,
        "failedStages": failed,
        "nonSuccessStages": non_success,
        "packageStages": package_stages,
        "failedPackageStages": failed_package,
        "nonSuccessPackageStages": non_success_package,
        "ensureResultPackageOutcome": ensure_result_package,
        "recoveryOutcome": "success",
        "stageOutcomeMap": {name: outcome for name, outcome in stage_outcomes},
        "stageOutcomes": stages,
        "staticChecksOutcome": outcome_by_name["staticChecks"],
        "projectVerificationOutcome": outcome_by_name["projectVerification"],
        "buildOutcome": outcome_by_name["macBuild"],
        "macBuildOutcome": outcome_by_name["macBuild"],
        "iosBuildOutcome": outcome_by_name["iosBuild"],
        "testOutcome": outcome_by_name["projectVerification"],
        "projectSpecificReports": PROJECT_SPECIFIC_REPORTS,
    }
    write_json(root / "ci-artifact-manifest.json", manifest)

    tests = [
        ("staticChecks", outcome_by_name["staticChecks"], "ci-results/static-checks.log"),
        ("projectVerification", outcome_by_name["projectVerification"], "ci-results/verify_project.log"),
        ("macBuild", outcome_by_name["macBuild"], "ci-results/xcodebuild.log"),
        ("iosBuild", outcome_by_name["iosBuild"], "ci-results/ios-xcodebuild.log"),
    ]
    suite = ET.Element("testsuite", name="ChronoFocus CI Results", tests="4", failures=str(sum(outcome != "success" for _, outcome, _ in tests)), errors="0")
    for name, outcome, log_path in tests:
        case = ET.SubElement(suite, "testcase", name=name, classname="ChronoFocusCI")
        ET.SubElement(case, "system-out").text = f"outcome={outcome}; log={log_path}"
        if outcome != "success":
            ET.SubElement(case, "failure", message=f"{name} {outcome}").text = f"See {log_path}"
    ET.ElementTree(suite).write(root / "junit.xml", encoding="utf-8", xml_declaration=True)

    lines = [
        "# ChronoFocus CI Failure Summary",
        "",
        f"- Version: `{manifest['version']}`",
        f"- Branch: `{branch}`",
        f"- Commit: `{commit}`",
        f"- Run: `{run_id}` attempt `{attempt}`",
        "- Overall outcome: `failure`",
        f"- Checkout: `{outcome_by_name['checkout']}`",
        f"- Prepare result metadata: `{outcome_by_name['prepareMetadata']}`",
        f"- Select Xcode: `{outcome_by_name['selectXcode']}`",
        f"- Static checks: `{outcome_by_name['staticChecks']}`",
        f"- Project verification: `{outcome_by_name['projectVerification']}`",
        f"- Mac build: `{outcome_by_name['macBuild']}`",
        f"- iOS build: `{outcome_by_name['iosBuild']}`",
        f"- Bootstrap result package: `{outcome_by_name['bootstrap']}`",
        f"- Create manifest: `{outcome_by_name['createManifest']}`",
        f"- Ensure result package: `{ensure_result_package}`",
        f"- Recovery result package: `success`",
        f"- Fallback artifact name: `{fallback_name}`",
        f"- Fallback artifact used: `{str(fallback_used).lower()}`",
        f"- Failure mode: `{failure_mode}`",
        f"- First failed stage: `{first_failed or 'none'}`",
        "- Stage outcomes: `ci-results/ci-stage-outcomes.json`",
        "",
        "## Logs",
        "",
        "- Static checks: `ci-results/static-checks.log`",
        "- Project verification: `ci-results/verify_project.log`",
        "- Mac build: `ci-results/xcodebuild.log`",
        "- Xcode result bundle: `ci-results/ChronoFocusMac.xcresult`",
        "- iOS build: `ci-results/ios-xcodebuild.log`",
        "- iOS Xcode result bundle: `ci-results/ChronoFocus-iOS.xcresult`",
        "- Mac snapshots: `ci-results/project-reports/mac-snapshots/`",
    ]
    if all_non_success:
        lines.extend(["", "## Failed Stages", ""])
        lines.extend(f"- `{name}`: `{outcome_by_name[name]}`" for name in all_non_success)
        lines.extend(["", "## Failure Excerpts", "", "Result package recovery rebuilt this fallback summary."])
        for name in all_non_success:
            lines.extend([f"### `{name}`", "", "```text"])
            lines.extend(log_excerpt(name, outcome_by_name[name]))
            lines.extend(["```", ""])
    else:
        lines.append("All CI stages passed.")
    (root / "ci-failure-summary.md").write_text("\n".join(lines) + "\n", encoding="utf-8")

    paths = list(EXPECTED_PATHS)
    if outcome_by_name["prepareMetadata"] != "success":
        paths.append("ci-results/prepare-metadata.log")
    required_paths = set(REQUIRED_FAILURE_PATHS)
    entries = [path_metadata(path, path in required_paths) for path in paths]
    missing_artifact_paths = [
        entry["path"] for entry in entries if not entry["required"] and not entry["exists"]
    ]
    stage_payload["missingArtifactPaths"] = missing_artifact_paths
    manifest["missingArtifactPaths"] = missing_artifact_paths
    write_json(root / "ci-stage-outcomes.json", stage_payload)
    write_json(root / "ci-artifact-manifest.json", manifest)
    index = {
        "version": os.environ["CI_PROCESS_VERSION"],
        "artifactName": artifact_name,
        "branch": branch,
        "commitSha": commit,
        "runId": run_id,
        "runAttempt": attempt,
        "createdAt": created_at,
        "overallOutcome": "failure",
        "failureMode": failure_mode,
        "fallbackArtifactName": fallback_name,
        "fallbackArtifactUsed": fallback_used,
        "stageOutcomes": stages,
        "packageStages": package_stages,
        "firstFailedStage": first_failed,
        "failedStages": failed,
        "nonSuccessStages": non_success,
        "failedPackageStages": failed_package,
        "nonSuccessPackageStages": non_success_package,
        "ensureResultPackageOutcome": ensure_result_package,
        "recoveryOutcome": "success",
        "stageOutcomeMap": {name: outcome for name, outcome in stage_outcomes},
        "missingArtifactPaths": missing_artifact_paths,
        "entries": entries,
    }
    index_path = root / "ci-artifact-index.json"
    index_path.write_text("{}\n", encoding="utf-8")
    stable = False
    for _ in range(20):
        entries = [path_metadata(path, path in required_paths) for path in paths]
        index["entries"] = entries
        index["missingArtifactPaths"] = [
            entry["path"] for entry in entries if not entry["required"] and not entry["exists"]
        ]
        index["totals"] = {
            "entryCount": len(entries),
            "missingRequiredCount": sum(entry["required"] and not entry["exists"] for entry in entries),
            "fileByteCount": sum(entry.get("byteCount", 0) for entry in entries),
            "directoryRecursiveByteCount": sum(entry.get("recursiveByteCount", 0) for entry in entries),
        }
        write_json(index_path, index)
        actual_entries = [path_metadata(path, path in required_paths) for path in paths]
        if actual_entries == entries:
            stable = True
            break
    if not stable:
        raise RuntimeError("Could not stabilize ci-artifact-index.json self metadata")
    entries_by_path = {entry["path"]: entry for entry in entries}
    invalid_required_paths = [
        path
        for path in sorted(REQUIRED_FAILURE_PATHS)
        if not valid_required_entry(path, entries_by_path.get(path))
    ]
    if invalid_required_paths:
        raise RuntimeError(
            "Recovered fallback package is missing required paths: "
            + ", ".join(invalid_required_paths)
        )
    print(f"Recovered fallback artifact package: {artifact_name}")


if __name__ == "__main__":
    main()
